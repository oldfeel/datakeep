#!/bin/bash
# gui.files.go 缺 !noassets 时会与 noassets.go 的 Assets 冲突
set -euo pipefail
GUI_FILES="$(cd "$(dirname "$0")" && pwd)/../../syncthing/lib/api/auto/gui.files.go"
[[ -f "$GUI_FILES" ]] || exit 0
grep -q 'go:build !noassets' "$GUI_FILES" && exit 0

echo "→ 为 gui.files.go 补上 //go:build !noassets"
python3 - "$GUI_FILES" <<'PY'
import sys
from pathlib import Path

p = Path(sys.argv[1])
text = p.read_text()
marker = "// Code generated by genassets.go - DO NOT EDIT.\n"
tag = marker + "\n//go:build !noassets\n// +build !noassets\n"
if text.startswith(marker):
    rest = text[len(marker) :].lstrip("\n")
    p.write_text(tag + "\n" + rest)
else:
    p.write_text("//go:build !noassets\n// +build !noassets\n\n" + text)
PY
